def eval_fixture_equation(expression, *, time):
    """Whitelisted Fraction evaluator solely for the public capability fixture.

    ast.FloorDiv means Buffalo safe division, NEVER Python floor division.
    Not used to interpret native Buffalo generations or replace its simulator.
    """
    bindings = {"TIME": Fraction(time), "Pulse_rate": Fraction("1.7"),
                "Start_time": Fraction(0), "End_time": Fraction(2)}
    root = ast.parse(expression.replace("^", "**"), mode="eval")

    def walk(node):
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            return Fraction(str(node.value))
        if isinstance(node, ast.Name) and node.id in bindings:
            return bindings[node.id]
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
            value = walk(node.operand)
            return value if isinstance(node.op, ast.UAdd) else -value
        if isinstance(node, ast.BinOp):
            left, right = walk(node.left), walk(node.right)
            if isinstance(node.op, ast.Add):
                return left + right
            if isinstance(node.op, ast.Sub):
                return left - right
            if isinstance(node.op, ast.Mult):
                return left * right
            if isinstance(node.op, ast.Div):
                return left / right
            if isinstance(node.op, ast.FloorDiv):
                return Fraction(0) if right == 0 else left / right
            if isinstance(node.op, ast.Pow) and right.denominator == 1:
                return left ** int(right)
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
            and not node.keywords and node.func.id.upper() == "MAX"
            and len(node.args) == 2):
            return max(walk(node.args[0]), walk(node.args[1]))
        raise ValueError("UNSUPPORTED_PUBLIC_PULSE_FIXTURE_EXPRESSION")

    return walk(root.body)


