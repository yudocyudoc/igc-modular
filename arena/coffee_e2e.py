def b_mapping(native):
    stocks = [v for v in native["model"]["variables"] if v["type"] == "stock"]
    terminal = [v for v in stocks if not v.get("outflows") and
                "pick" in v["name"].lower() and "cumul" in v["name"].lower()]
    need(len(stocks) == 2 and len(terminal) == 1, "B_NATIVE_PICKUP_MAPPING_UNSUPPORTED")
    counter = terminal[0]
    waiting = next(v for v in stocks if v is not counter)
    need(len(counter.get("inflows", [])) == 1 and
         counter["inflows"][0] in waiting.get("outflows", []) and
         all(float(v["equation"]) == 0 for v in stocks),
         "B_NATIVE_MATERIAL_FRONTIER_UNSUPPORTED")
    loss = [ident(f) for f in waiting["outflows"] if f not in counter["inflows"]]
    return {"counter": ident(counter["name"]), "waiting": ident(waiting["name"]),
            "loss_flows": loss, "mapping_basis": "AUTHENTIC_NATIVE_PICKUP_STOCK_AND_MATERIAL_PORTS"}


def project(rows, counter):
    need(rows and rows[0]["time"] <= 0 and
         abs(rows[-1]["time"]-solver.HORIZON) <= 1e-6, "TRACE_COVERAGE")
    result = {}
    for cut in CUTS:
        prior = [r[counter] for r in rows if r["time"]*60 <= cut+1e-8]
        need(bool(prior), "NO_SAMPLE_BEFORE_CUT")
        result[str(cut)] = {"orders_picked_up_cumulative": prior[-1]}
    return result


def verify_b_csv(path, native):
    mapping = b_mapping(native)
    columns = ["time", mapping["counter"], mapping["waiting"], *mapping["loss_flows"]]
    with Path(path).open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        need(reader.fieldnames and len(set(reader.fieldnames)) == len(reader.fieldnames)
             and set(columns) <= set(reader.fieldnames), "B_CSV_COLUMNS")
        rows = []
        for r in reader:
            need(len(rows) < 10000, "B_CSV_TOO_LARGE")
            values = {k: float(r[k]) for k in columns}
            need(all(math.isfinite(v) for v in values.values()), "B_CSV_NONFINITE")
            rows.append(values)
    need(len(rows) >= 65, "B_CSV_INCOMPLETE")
    loss_integral, previous, worst = 0.0, None, 0.0
    for r in rows:
        if previous is not None:
            dt = r["time"]-previous["time"]
            need(dt >= 0 and r[mapping["counter"]]+1e-8 >= previous[mapping["counter"]],
                 "B_CSV_NOT_MONOTONE")
            loss_integral += dt*sum(previous[k] for k in mapping["loss_flows"])
        need(min(r[k] for k in columns if k != "time") >= -1e-8, "B_CSV_NEGATIVE")
        residual = abs(r[mapping["counter"]]+r[mapping["waiting"]]+loss_integral-10*r["time"])
        worst = max(worst, residual)
        need(residual <= solver.MASS_TOLERANCE, "B_CSV_MATERIAL_BALANCE")
        previous = r
    return {"mapping": mapping, "samples": len(rows), "mass_balance_max_abs_orders": worst,
            "predictions": project(rows, mapping["counter"])}


def stage_native(out, api=None, *, preflight=False):
    if preflight:
        e = os.environ
        need(e.get("GITHUB_REPOSITORY") == REPO and
             e.get("GITHUB_EVENT_NAME") in ("push", "pull_request") and
             re.fullmatch(r"[1-9][0-9]*", e.get("GITHUB_RUN_ID", "")) and
             re.fullmatch(r"[0-9a-f]{40}", e.get("GITHUB_SHA", "")),
             "PUBLIC_NATIVE_PREFLIGHT_REQUIRES_GITHUB")
        run_id, sha = int(e["GITHUB_RUN_ID"]), e["GITHUB_SHA"]
    else:
        run_id, sha = execution_identity()
    need(not any(os.environ.get(k) for k in dm.NO_R2), "PRODUCER_PRIVATE_CREDENTIAL")
    api = api or api_client()
    out = Path(out)
    out.mkdir(parents=True, exist_ok=False, mode=0o700)
    g2, r0, r1, audit = native_sources(api)
    verified, proof = feedback._verify_g2(g2)
    public = out/"public"
    public.mkdir()
    for name in ("producer-public-b0.json", "release.json"):
        (public/name).write_bytes(g2["input/public/"+name])
    prepare_dm(public, dm.ASSUMPTIONS, out/"regenerated", environment={})
    candidates = []
    for arm in ("D", "M"):
        regenerated = read_json(out/"regenerated"/arm/"manifest.json")
        for i, candidate in enumerate(verified[arm]):
            need(regenerated["candidates"][i] == candidate["native_parent"],
                 "REGENERATED_ORIGINAL_DIFFERS_FROM_CACHED_PHYSICAL_MODEL")
            candidates.append({k: candidate[k] for k in
                               ("arm", "candidate_id", "model_sha256", "csv_sha256", "predictions")})
            candidates[-1].update(status="PREDICTED", execution="AUTHENTICATED_G2_CACHE_REUSED")
    # Invoke unchanged own D/M policies and recover their parent-scoped ATMS feedback.
    feedback.connect(g2, r0, out/"feedback")
    native = json.loads(r1["provider/native-engine-result.json"])
    cls, mo, translation = translate_b(native)
    need(mo.encode() == r1["provider/translated.mo"], "B_TRANSLATION_CHANGED")
    b_mapping(native)
    (out/"B.mo").write_text(mo, encoding="utf-8", newline="\n")
    write_json(out/"B-native.json", native, exclusive=True)
    script = (f'loadFile("B.mo");\ncheckModel({cls});\nprint(getErrorString());\n'
              f'simulate({cls}, startTime=0, stopTime={solver.HORIZON:.16g}, '
              'numberOfIntervals=64, method="euler", outputFormat="csv", fileNamePrefix="B");\n'
              'print(getErrorString());\n')
    (out/"B.mos").write_text(script, encoding="utf-8", newline="\n")
    write_json(out/"stage.json", {
        "schema": SCHEMA, "run_id": run_id, "code_sha": sha,
        "case_sha256": dm.CASE_SHA256, "public_sha256": dm.PUBLIC_SHA256,
        "dm_candidates": candidates, "dm_cache": proof,
        "B_class": cls, "B_translation": translation,
        "B_native_file_sha256": "sha256:"+corpus.sha_file(out/"B-native.json"),
        "B_model_sha256": "sha256:"+corpus.sha_file(out/"B.mo"),
        "B_script_sha256": "sha256:"+corpus.sha_file(out/"B.mos"),
        "B_own_revision": audit, "max_new_omc": 1, "new_provider_posts": 0,
        "truth_access": False}, exclusive=True)
    return {"status": "NATIVE_MODELS_AND_OWN_FEEDBACK_STAGED", "dm_regenerated": 12,
            "dm_cached_simulations": 12, "B_pending_omc": 1, "provider_posts": 0}


