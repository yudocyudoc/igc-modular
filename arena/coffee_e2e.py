def run_b(out, cli=subprocess.run):
    run_id, sha = execution_identity()
    need(not any(os.environ.get(k) for k in dm.NO_R2), "SOLVER_PRIVATE_CREDENTIAL")
    out = Path(out).resolve()
    stage = read_json(out/"stage.json")
    attempt = read_json(out/"B-attempt.json")
    need(attempt["run_id"] == stage["run_id"] == run_id and
         attempt["code_sha"] == stage["code_sha"] == sha and
         attempt["max_new_omc"] == 1 and not (out/"B-result.json").exists(), "B_ATTEMPT_INVALID")
    for file, key in (("B.mo", "B_model_sha256"), ("B.mos", "B_script_sha256"),
                      ("B-native.json", "B_native_file_sha256")):
        need("sha256:"+corpus.sha_file(out/file) == stage[key], "B_INPUT_CHANGED_AFTER_STAGE")
    result = {"status": "FAILED_G2", "new_omc_attempts": 1, "provider_posts": 0,
              "retry": False, "predictions": None}
    args = ["docker", "run", "--rm", "--network", "none", "--user",
            f"{os.getuid()}:{os.getgid()}", "-e", "HOME=/tmp", "-v", f"{out}:/work", "-w", "/work",
            runtime.IMAGE, "omc", "B.mos"]
    try:
        # OMC's simulation runtime itself writes <fileNamePrefix>.log.
        # Capturing omc stdout to B.log lets that runtime truncate compiler proof.
        with (out/"B-omc.log").open("xb") as log:
            outcome = cli(args, stdout=log, stderr=subprocess.STDOUT, timeout=180,
                          check=False, env={k:v for k,v in os.environ.items()
                                           if k not in ("GH_TOKEN", "GITHUB_TOKEN")})
        text = (out/"B-omc.log").read_text(encoding="utf-8", errors="replace")
        need(outcome.returncode == 0 and "LOG_SUCCESS" in text and
             f"Check of {stage['B_class']} completed successfully" in text and
             "Simulation execution failed" not in text, "B_OMC_NOT_SUCCESSFUL")
        checked = verify_b_csv(out/"B_res.csv", read_json(out/"B-native.json"))
        result.update(checked)
        result.update(status="PREDICTED", csv_sha256="sha256:"+corpus.sha_file(out/"B_res.csv"))
    except (ArenaError, OSError, subprocess.TimeoutExpired, ValueError, KeyError) as exc:
        result["failure"] = str(exc) if isinstance(exc, ArenaError) else type(exc).__name__
    write_json(out/"B-result.json", result, exclusive=True)
    return result


def make_lock(native_dir, out):
    run_id, sha = execution_identity()
    root, out = Path(native_dir), Path(out)
    out.mkdir(parents=True, exist_ok=False)
    stage, b = read_json(root/"stage.json"), read_json(root/"B-result.json")
    need(stage["run_id"] == run_id and stage["code_sha"] == sha, "WRONG_NATIVE_RUN")
    candidates = list(stage["dm_candidates"])
    candidates.append({"arm": "B", "candidate_id": "B_ORIGINAL_R1",
                       "status": b["status"], "model_sha256": stage["B_model_sha256"],
                       "csv_sha256": b.get("csv_sha256"), "predictions": b["predictions"],
                       "execution": "ONE_NEW_ORIGINAL_R1_OMC_ATTEMPT"})
    lock = {"schema": LOCK_SCHEMA, "mode": "SCIENTIFIC", "run_id": run_id,
            "code_sha": sha, "case_sha256": dm.CASE_SHA256,
            "public_sha256": dm.PUBLIC_SHA256, "source_sha256": SOURCE_SHA,
            "selection": dm.SELECTION, "prediction_cuts_min": list(CUTS),
            "observation": "orders_picked_up_cumulative", "candidates": candidates,
            "candidate_selection": "ALL_6_D_6_M_AND_ORIGINAL_B_R1_NO_POSTHOC_WINNER",
            "new_provider_posts": 0, "new_omc_attempts": 1,
            "cached_dm_simulations": 12, "truth_access": False,
            "evaluation_scope": "FROZEN_V1_RETROSPECTIVE_SYNTHETIC_CONTRAST_NOT_NEW_INDEPENDENT_WORLD"}
    validate_lock(lock)
    write_json(out/"lock.json", lock, exclusive=True)
    for name in ("stage.json", "B-native.json", "B.mo", "B.mos", "B-attempt.json",
                 "B-result.json", "B.log", "B-omc.log", "B_res.csv"):
        if (root/name).is_file():
            (out/name).write_bytes((root/name).read_bytes())
    # feedback summary gives own-policy outcomes without leaking another arm's DB.
    (out/"own-feedback-summary.json").write_bytes((root/"feedback/summary.json").read_bytes())
    return {"status": "PREDICTIONS_SEALED_BEFORE_TRUTH", "candidates": len(candidates),
            "lock_sha256": digest(lock), "B_status": b["status"]}


def validate_lock(lock):
    need(lock.get("schema") == LOCK_SCHEMA and lock.get("mode") == "SCIENTIFIC"
         and lock.get("case_sha256") == dm.CASE_SHA256 and
         lock.get("source_sha256") == SOURCE_SHA and lock.get("selection") == dm.SELECTION
         and lock.get("public_sha256") == dm.PUBLIC_SHA256 and
         lock.get("truth_access") is False and lock.get("prediction_cuts_min") == list(CUTS),
         "SCIENTIFIC_LOCK_OR_POPULATION_INVALID")
    candidates = lock.get("candidates", [])
    need(len(candidates) == 13 and
         {a:sum(c.get("arm") == a for c in candidates) for a in ("D", "M", "B")} ==
         {"D":6, "M":6, "B":1} and len({c["candidate_id"] for c in candidates}) == 13,
         "LOCK_DENOMINATOR_CHANGED")
    for c in candidates:
        need(c.get("status") in ("PREDICTED", "FAILED_G2"), "LOCK_CANDIDATE_STATUS")
        if c["status"] == "PREDICTED":
            need(set(c.get("predictions", {})) == {str(t) for t in CUTS}, "LOCK_FORECAST_CUTS")
            previous = -1.0
            for cut in CUTS:
                value = c["predictions"][str(cut)].get("orders_picked_up_cumulative")
                need(type(value) in (int, float) and math.isfinite(value) and
                     value >= previous and value >= 0, "LOCK_FORECAST_VALUE")
                previous = value
        else:
            need(c["arm"] == "B" and c.get("predictions") is None, "FAILED_MODEL_HAS_PREDICTIONS")
    return True


def verify_archived_lock(api, run_id, code_sha):
    run = api.run(run_id)
    need(run.get("id") == run_id and run.get("head_sha") == code_sha and
         run.get("path") == WORKFLOW and run.get("head_branch") == "main" and
         run.get("run_attempt") == 1, "LOCK_GITHUB_RUN_IDENTITY")
    listing = api.repo("GET", f"/actions/runs/{run_id}/artifacts?per_page=100")
    candidates = [x for x in listing.get("artifacts", [])
                  if x.get("name") == f"coffee-e2e-lock-{run_id}" and not x.get("expired")]
    need(listing.get("total_count", 101) <= 100 and len(candidates) == 1,
         "LOCK_ARTIFACT_NOT_UNIQUE")
    meta = api.repo("GET", f"/actions/artifacts/{candidates[0]['id']}")
    need(meta.get("workflow_run", {}).get("id") == run_id and not meta.get("expired"),
         "LOCK_GITHUB_ARTIFACT_IDENTITY")
    raw = api.repo("GET", f"/actions/artifacts/{meta['id']}/zip", binary=True)
    entries = feedback._safe_archive(raw, expected_digest=meta["digest"])
    lock = json.loads(entries["lock.json"])
    validate_lock(lock)
    need(lock["run_id"] == run_id and lock["code_sha"] == code_sha, "LOCK_EXECUTION_CHANGED")
    # Recompute forecasts from the exact authenticated native outputs BEFORE R2.
    g2 = fetch_historical(api, 4)
    verified, _ = feedback._verify_g2(g2)
    actual_dm = {(c["arm"], c["candidate_id"]): c for a in ("D", "M") for c in verified[a]}
    for c in lock["candidates"]:
        if c["arm"] != "B":
            actual = actual_dm.get((c["arm"], c["candidate_id"]))
            need(actual and all(c[k] == actual[k] for k in
                               ("model_sha256", "csv_sha256", "predictions")), "LOCK_MODEL_FORECAST_DECOUPLED")
    r1 = fetch_historical(api, 7)
    native = json.loads(r1["provider/native-engine-result.json"])
    _, mo, _ = translate_b(native)
    need(entries["B.mo"] == mo.encode() and json.loads(entries["B-native.json"]) == native,
         "LOCK_B_NATIVE_CHANGED")
    b = next(c for c in lock["candidates"] if c["arm"] == "B")
    need(b["model_sha256"] == "sha256:"+__import__('hashlib').sha256(entries["B.mo"]).hexdigest(),
         "LOCK_B_MODEL_HASH")
    attempt = json.loads(entries["B-attempt.json"])
    need(attempt["run_id"] == run_id and attempt["code_sha"] == code_sha and
         attempt["max_new_omc"] == 1 and attempt["attempt_reserved"] is True,
         "LOCK_B_ATTEMPT_NOT_AUTHENTIC")
    if b["status"] == "PREDICTED":
        need("LOG_SUCCESS" in entries["B.log"].decode("utf-8", errors="replace"), "LOCK_B_SOLVER_NOT_SUCCESS")
        with TemporaryDirectory() as tmp:
            path = Path(tmp)/"B.csv"
            path.write_bytes(entries["B_res.csv"])
            checked = verify_b_csv(path, native)
            need(checked["predictions"] == b["predictions"] and
                 "sha256:"+corpus.sha_file(path) == b["csv_sha256"], "LOCK_B_FORECAST_DECOUPLED")
    return lock, {"artifact_id": meta["id"], "artifact_digest": meta["digest"],
                  "native_coupling_verified_before_truth": True}


def score_pickups(lock, oracle):
    validate_lock(lock)
    rows = []
    for c in lock["candidates"]:
        row = {"arm": c["arm"], "candidate_id": c["candidate_id"], "status": c["status"]}
        if c["status"] == "PREDICTED":
            errors = [c["predictions"][str(t)]["orders_picked_up_cumulative"]-
                      oracle["metrics"][str(t)]["orders_picked_up_cumulative"] for t in CUTS]
            row.update(mae_pickups_orders=sum(abs(x) for x in errors)/3,
                       rmse_pickups_orders=math.sqrt(sum(x*x for x in errors)/3),
                       signed_errors_orders=errors)
        else:
            row.update(mae_pickups_orders=None, rmse_pickups_orders=None, signed_errors_orders=None)
        rows.append(row)
    return rows


