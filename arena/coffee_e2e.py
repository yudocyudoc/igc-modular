def private_storage():
    # Keep the proven R2 transport and bucket; permit this explicit new namespace.
    class CoffeeV2Storage(R2Storage):
        @staticmethod
        def _key(key):
            need(isinstance(key, str) and key.startswith("coffee-peak/") and
                 ".." not in key and "\\" not in key and "//" not in key,
                 "PRIVATE_KEY_INVALID")
            return key
    return CoffeeV2Storage()


def private_run_prefix(run_id):
    need(re.fullmatch(r"[1-9][0-9]*", str(run_id)), "BAD_RUN_ID")
    return f"{PREFIX}runs/{run_id}/"


def prepare_corpus(out, storage=None):
    run_id, sha = execution_identity()
    storage = storage or private_storage()
    out = Path(out)
    out.mkdir(parents=True, exist_ok=False, mode=0o700)
    source = out / "source.zip"
    storage.get(source_key(SOURCE_SHA), source)
    key_name = f"{PREFIX}corpus/{SOURCE_SHA}/partition-key.bin"
    # List only this exact key. Errors never mean 'missing'; no key rotation.
    listing = storage.client.call("s3api", "list-objects-v2", "--bucket",
                                  storage.client.bucket, "--prefix", key_name)
    matching = [r for r in listing.get("Contents", []) if r["Key"] == key_name]
    need(len(matching) <= 1, "AMBIGUOUS_PARTITION_KEY")
    key_file = out / "partition-key.bin"
    if matching:
        storage.get(key_name, key_file)
    else:
        key_file.write_bytes(secrets.token_bytes(32))
        storage.put_once(key_name, key_file)
    key = key_file.read_bytes()
    result = corpus.audit(source, key=key)
    corpus.export(result, private_out=out/"custody", public_out=out/"census", key=key)
    packet = views.build(source, out/"custody")
    views.export(packet, out/"views")
    need({p.name for p in (out/"views").iterdir()} == VIEW_FILES,
         "VIEW_ALLOWLIST_CHANGED")
    for name in sorted(VIEW_FILES):
        storage.put_once(private_run_prefix(run_id)+"views/"+name, out/"views"/name)
    summary = {"schema": SCHEMA, "status": "CORPUS_PREPARED_IN_EXISTING_R2",
               "run_id": run_id, "code_sha": sha, "source_sha256": SOURCE_SHA,
               "weekly_cases": result["public"]["synthetic_weekly_runs"],
               "released_weeks": 45, "reserved_weeks": 9,
               "pos_rows": result["public"]["pos_synthetic_rows"],
               "line_item_rows": result["public"]["pos_line_item_rows"],
               "truth_parsed": False, "new_worlds": 0, "provider_posts": 0}
    # Only this aggregate file may be uploaded from this job.
    write_json(out/"admission-summary.json", summary, exclusive=True)
    return summary


